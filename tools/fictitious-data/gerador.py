"""Generates the fictitious dataset as SQL, in the demo or the volume size."""

import argparse
import sys
import time
from datetime import date
from pathlib import Path

import escritor_sql
import invariantes
import massa

SEMENTE_PADRAO = 2026


def cabecalho(tamanho: str, semente: int, com_saida_producao: bool, data_referencia: date | None) -> str:
    opcoes = f"--tamanho {tamanho} --semente {semente}"
    if data_referencia is not None:
        opcoes += f" --data-referencia {data_referencia.isoformat()}"
    if com_saida_producao:
        opcoes += " --com-saida-producao"
    return f"Generated by tools/fictitious-data/gerador.py {opcoes}. Do not edit by hand."


def _argumentos(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Fictitious dataset generator")
    parser.add_argument("--tamanho", choices=("demo", "volume"), required=True)
    parser.add_argument("--semente", type=int, default=SEMENTE_PADRAO)
    parser.add_argument("--saida", type=Path)
    parser.add_argument("--data-referencia", type=date.fromisoformat,
                        help="last day of the volume history; volume only, defaults to today")
    parser.add_argument("--verificar", action="store_true", help="print the counts and fail on a broken invariant")
    parser.add_argument("--com-saida-producao", action="store_true",
                        help="also write the SAIDA_PRODUCAO movements of the orders that reached production")
    argumentos = parser.parse_args(argv)
    if argumentos.tamanho == "demo" and argumentos.data_referencia is not None:
        parser.error("--data-referencia only applies to the volume size")
    if argumentos.saida is None and not argumentos.verificar:
        parser.error("provide --saida, --verificar or both")
    return argumentos


def _relatar(m: massa.Massa) -> None:
    for tabela, quantidade in invariantes.contagens(m).items():
        print(f"{tabela}: {quantidade}")
    print("pedidos por status:")
    for status, quantidade in invariantes.contagem_por_status(m).items():
        print(f"  {status}: {quantidade}")


def main(argv: list[str] | None = None) -> int:
    argumentos = _argumentos(argv)
    inicio = time.perf_counter()

    data_referencia = None
    if argumentos.tamanho == "demo":
        m = massa.gerar_demo(argumentos.semente, argumentos.com_saida_producao)
    else:
        data_referencia = argumentos.data_referencia or date.today()
        m = massa.gerar_volume(argumentos.semente, com_saida_producao=argumentos.com_saida_producao)

    if argumentos.saida is not None:
        argumentos.saida.parent.mkdir(parents=True, exist_ok=True)
        with argumentos.saida.open("w", encoding="utf-8", newline="\n") as saida:
            texto = cabecalho(argumentos.tamanho, argumentos.semente, argumentos.com_saida_producao, data_referencia)
            escritor_sql.escrever(m, saida, texto, data_referencia)

    if argumentos.verificar:
        _relatar(m)
        erros = invariantes.verificar(m)
        for erro in erros:
            print(f"INVARIANT VIOLATED: {erro}", file=sys.stderr)
        print(f"tempo: {time.perf_counter() - inicio:.1f} s")
        if erros:
            return 1
        print("invariantes: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
